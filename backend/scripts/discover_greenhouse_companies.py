JOBS_API = "https://boards-api.greenhouse.io/v1/boards/{}/jobs"
BOARD_API = "https://boards-api.greenhouse.io/v1/boards/{}"


def slug_to_name(slug: str) -> str:
    """Best-effort human name from a slug when no other source is available."""
    s = re.sub(r"[-_]", " ", slug)
    s = re.sub(r"([a-z])([A-Z])", r"\1 \2", s)
    return s.title()


async def check_slug(
    session: aiohttp.ClientSession,
    hint_name: str,
    slug: str,
    sem: asyncio.Semaphore,
    resolve_name: bool = False,
) -> Optional[dict]:
    if slug in EXISTING_SLUGS:
        return None
    async with sem:
        try:
            async with session.get(
                JOBS_API.format(slug), timeout=aiohttp.ClientTimeout(total=12)
            ) as resp:
                if resp.status != 200:
                    return None
                data = await resp.json(content_type=None)
                jobs = data.get("meta", {}).get("total") or len(data.get("jobs", []))
                name = hint_name
                # When we only have a slug, try the board-info endpoint for a real name
                if resolve_name:
                    try:
                        async with session.get(
                            BOARD_API.format(slug),
                            timeout=aiohttp.ClientTimeout(total=8),
                        ) as br:
                            if br.status == 200:
                                bd = await br.json(content_type=None)
                                name = bd.get("name") or name
                    except Exception:
                        pass
                return {"name": name, "slug": slug, "jobs": jobs}
        except Exception:
            pass
    return None


async def discover(candidates: list, concurrency: int, resolve_name: bool):
    sem = asyncio.Semaphore(concurrency)
    connector = aiohttp.TCPConnector(limit=concurrency, ssl=False)
    async with aiohttp.ClientSession(connector=connector) as session:
        tasks = [
            check_slug(session, name, slug, sem, resolve_name)
            for name, slug in candidates
        ]
        results = []
        done = 0
        total = len(tasks)
        for coro in asyncio.as_completed(tasks):
            result = await coro
            done += 1
            if result:
                results.append(result)
                print(f"  ✓ {result['name']} ({result['slug']}) — {result['jobs']} jobs")
            if done % 100 == 0:
                print(f"[{done}/{total}] checked, {len(results)} found so far...")
        return results


def main():
    parser = argparse.ArgumentParser(description="Discover Greenhouse companies")
    parser.add_argument("--from-file", type=str, default=None,
                        help="JSON file with a list of slugs (e.g. from Feashliaa dataset)")
    parser.add_argument("--min-jobs", type=int, default=1, help="Min jobs to include (default: 1)")
    parser.add_argument("--concurrency", type=int, default=50, help="Concurrent requests (default: 50)")
    parser.add_argument("--output", type=str, default=None, help="Save results to CSV file")
    parser.add_argument("--no-resolve-name", action="store_true",
                        help="Skip the extra board-info call to resolve company names (faster)")
    args = parser.parse_args()

    if args.from_file:
        with open(args.from_file) as f:
            raw_slugs = json.load(f)
        # Filter out already-tracked and obvious garbage
        candidates = [
            (slug_to_name(s), s)
            for s in raw_slugs
            if s not in EXISTING_SLUGS and len(s) >= 3 and not re.match(r"^\d+$", s)
        ]
        resolve_name = not args.no_resolve_name
        print(f"Loaded {len(raw_slugs)} slugs from {args.from_file}")
        print(f"After filtering known companies: {len(candidates)} to check")
    else:
        candidates = [(name, slug) for name, slug in SEED if slug not in EXISTING_SLUGS]
        resolve_name = False
        print(f"Using built-in seed list: {len(candidates)} candidates")

    print(f"Skipping {len(EXISTING_SLUGS)} already-tracked companies.")
    print(f"Concurrency: {args.concurrency}, resolve names: {resolve_name}\n")

    start = time.time()
    results = asyncio.run(discover(candidates, args.concurrency, resolve_name))
    elapsed = time.time() - start

    confirmed = [r for r in results if r["jobs"] >= args.min_jobs]
    confirmed.sort(key=lambda x: x["jobs"], reverse=True)

    print(f"\n{'='*60}")
    print(f"Found {len(confirmed)} new Greenhouse companies (≥{args.min_jobs} jobs) in {elapsed:.1f}s\n")

    for r in confirmed:
        print(f"  {r['name']:<40} {r['slug']:<30} {r['jobs']:>5} jobs")

    if args.output:
        with open(args.output, "w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=["name", "slug", "jobs"])
            writer.writeheader()
            writer.writerows(confirmed)
        print(f"\nSaved to {args.output}")

    print(f"\ncompanies.py snippet:")
    print("-" * 60)
    for r in confirmed:
        slug = r["slug"]
        name = r["name"]
        print(f'    {{"slug": "{slug}", "name": "{name}", "ats": "greenhouse", "industry": "TBD"}},')


if __name__ == "__main__":
    main()
