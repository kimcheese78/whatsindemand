EXISTING_SLUGS = {c["slug"] for c in COMPANIES if c["ats"] == "greenhouse"}

# Also pull slugs from the prod DB so we don't re-add companies already scraped
def _load_db_slugs() -> set:
    db_url = os.environ.get("DATABASE_URL")
    if not db_url:
        print("DATABASE_URL not set — skipping DB slug check.")
        return set()
    try:
        import psycopg
        conn = psycopg.connect(db_url)
        cur = conn.cursor()
        cur.execute("SELECT greenhouse_slug FROM companies WHERE greenhouse_slug IS NOT NULL")
        slugs = {row[0] for row in cur.fetchall()}
        cur.close()
        conn.close()
        print(f"Loaded {len(slugs)} slugs from prod DB.")
        return slugs
    except Exception as e:
        print(f"Warning: could not load DB slugs ({e}). Falling back to companies.py only.")
        return set()

EXISTING_SLUGS |= _load_db_slugs()

